"""Generated reports. Deterministic: the same pack always produces the same text."""

from __future__ import annotations

from collections import defaultdict

from govpack.pack import STATUSES, Control, Mapping, Pack
from govpack.rules import Finding, catalog

HEADER = "<!-- Generated by govpack from frameworks/, mappings/, systems/ and evidence.lock.json. Do not edit by hand. -->\n"

NOTICE = (
    "> A mapping aid for engineers, architects and auditors. It records which controls have "
    "checked evidence in which repository and where there are gaps. It is not legal advice, not a "
    "conformity assessment and not a statement that any system complies with anything."
)

STATUS_MEANING = {
    "implemented": "A working technical control exists in code, tests or configuration.",
    "partial": "Some of what the control asks for exists; the limits say what is missing.",
    "designed": "A design or decision is documented; no running implementation in these repositories.",
    "organisational": "Needs people, policy or a legal decision that no repository can show. Supporting evidence may be listed.",
    "gap": "Applicable, and nothing here addresses it.",
}


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _row(*cells: str) -> str:
    return "| " + " | ".join(_esc(c) for c in cells) + " |"


def _short(sha: str) -> str:
    return sha[:12]


def _counts(pack: Pack, controls: list[Control]) -> dict[str, int]:
    out = dict.fromkeys(STATUSES, 0)
    for c in controls:
        m = pack.mapping(c.id)
        if m and m.status in out:
            out[m.status] += 1
    return out


def coverage(pack: Pack) -> str:
    lines = [HEADER, "# Coverage", "", NOTICE, "", "## Summary", ""]
    lines.append(_row("Framework", "Controls", *STATUSES))
    lines.append(_row("---", "---:", *("---:" for _ in STATUSES)))
    total = dict.fromkeys(STATUSES, 0)
    for f in pack.frameworks:
        cs = pack.controls_of(f.id)
        n = _counts(pack, cs)
        for k, v in n.items():
            total[k] += v
        lines.append(_row(f.name, str(len(cs)), *(str(n[s]) for s in STATUSES)))
    lines.append(
        _row("**All**", f"**{len(pack.controls)}**", *(f"**{total[s]}**" for s in STATUSES))
    )
    lines += ["", "## What the statuses mean", ""]
    lines += [f"- **{s}**: {STATUS_MEANING[s]}" for s in STATUSES]
    for f in pack.frameworks:
        lines += [
            "",
            f"## {f.name}",
            "",
            f"{f.citation}. Source: <{f.source}>. Control list last compared with the source on {f.checked}.",
        ]
        if f.note:
            lines += ["", f"_{f.note}_"]
        lines += [
            "",
            _row("Control", "Reference", "Title", "Applies to", "Status", "Evidence", "Reviewed"),
        ]
        lines.append(_row("---", "---", "---", "---", "---", "---:", "---"))
        for c in pack.controls_of(f.id):
            m = pack.mapping(c.id)
            lines.append(
                _row(
                    f"`{c.id}`", c.ref, c.title, c.applies_to,
                    m.status if m else "unmapped",
                    str(len(m.evidence)) if m else "0",
                    str(m.reviewed) if m else "",
                )
            )  # fmt: skip
    return "\n".join(lines) + "\n"


def gap_register(pack: Pack) -> str:
    lines = [HEADER, "# Gap register", "", NOTICE, ""]
    lines += [
        "Every control that is not `implemented`, with what is missing and who owns the next step. "
        "Order: gaps first, then organisational, designed, partial.",
        "",
    ]
    order = {"gap": 0, "organisational": 1, "designed": 2, "partial": 3}
    items = sorted(
        (m for m in pack.mappings if m.status in order and pack.control(m.control)),
        key=lambda m: (order[m.status], m.control),
    )
    lines.append(_row("Control", "Framework", "Status", "Owner", "What is missing", "Next step"))
    lines.append(_row("---", "---", "---", "---", "---", "---"))
    for m in items:
        c = pack.control(m.control)
        assert c is not None
        fw = pack.framework(c.framework)
        lines.append(
            _row(
                f"`{c.id}` {c.title}",
                fw.name if fw else c.framework,
                m.status,
                m.owner,
                m.limits or m.rationale,
                m.next_step,
            )
        )
    return "\n".join(lines) + "\n"


def evidence_index(pack: Pack) -> str:
    by_file: dict[str, list[tuple[Mapping, str, str]]] = defaultdict(list)
    for m, e in pack.evidence_items():
        by_file[e.key].append((m, e.kind, e.shows))
    lines = [HEADER, "# Evidence index", "", NOTICE, ""]
    lines += [
        f"{len(by_file)} files in {len(pack.repos)} registered repositories. The hash is the first 12 characters of the SHA-256 "
        f"pinned in `evidence.lock.json` (generated {pack.lock.generated or 'never'}). "
        "If a file changes, `govpack verify` fails until a person re-reads it and re-pins it.",
        "",
    ]
    for r in pack.repos:
        keys = sorted(k for k in by_file if k.startswith(r.name + ":"))
        if not keys:
            continue
        lines += [
            f"## [{r.name}]({r.url})",
            "",
            r.role,
            "",
            _row("File", "Kind", "SHA-256", "Supports"),
        ]
        lines.append(_row("---", "---", "---", "---"))
        for k in keys:
            path = k.split(":", 1)[1]
            entry = pack.lock.files.get(k)
            kinds = sorted({kind for _, kind, _ in by_file[k]})
            controls = ", ".join(
                f"`{m.control}`" for m, _, _ in sorted(by_file[k], key=lambda t: t[0].control)
            )
            lines.append(
                _row(
                    f"`{path}`",
                    "/".join(kinds),
                    _short(entry.sha256) if entry else "unpinned",
                    controls,
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def crosswalk(pack: Pack) -> str:
    """Controls in different frameworks that rest on the same evidence file."""
    ctrl_files: dict[str, set[str]] = {
        m.control: {e.key for e in m.evidence} for m in pack.mappings
    }
    lines = [HEADER, "# Crosswalk", "", NOTICE, ""]
    lines += [
        "Controls from different frameworks that cite the same evidence file. This is derived from the "
        "mappings, not an official equivalence between the frameworks: two controls sharing a file means "
        "the same repository artefact supports both, not that they ask for the same thing.",
        "",
    ]
    lines.append(_row("Shared evidence", *(f.name for f in pack.frameworks)))
    lines.append(_row("---", *("---" for _ in pack.frameworks)))
    by_file: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for m in pack.mappings:
        c = pack.control(m.control)
        if not c:
            continue
        for key in ctrl_files[m.control]:
            by_file[key][c.framework].append(c.id)
    shared = {k: v for k, v in by_file.items() if len(v) > 1}
    for key in sorted(shared):
        lines.append(
            _row(
                f"`{key}`",
                *(
                    ", ".join(f"`{c}`" for c in sorted(shared[key].get(f.id, []))) or "-"
                    for f in pack.frameworks
                ),
            )
        )
    lines += [
        "",
        f"{len(shared)} of {len(by_file)} evidence files support controls in more than one framework.",
    ]
    return "\n".join(lines) + "\n"


def system_record(pack: Pack) -> str:
    lines = [HEADER, "# AI system records", "", NOTICE, ""]
    for s in pack.systems:
        lines += [f"## {s.name}", "", s.summary, "", "| | |", "|---|---|"]
        lines += [
            _row("Intended purpose", s.intended_purpose),
            _row("Provider role", s.provider_role),
            _row("Deployer role", s.deployer_role),
            _row("Risk classification", s.risk_note),
            _row("Human oversight", s.oversight),
            _row("Logging", s.logging),
            _row("Data", s.data),
        ]
        lines += ["", "### Components", "", _row("Repository", "Role"), _row("---", "---")]
        for comp in s.components:
            r = pack.repo(comp.repo)
            lines.append(_row(f"[{comp.repo}]({r.url})" if r else comp.repo, comp.role))
        lines += ["", "### Known limitations", ""] + [f"- {x}" for x in s.limitations]
        lines += [
            "",
            "### Controls that apply",
            "",
            _row("Control", "Framework", "Status", "Owner"),
        ]
        lines.append(_row("---", "---", "---", "---"))
        for cid in s.controls:
            c = pack.control(cid)
            m = pack.mapping(cid)
            if c:
                fw = pack.framework(c.framework)
                lines.append(
                    _row(
                        f"`{cid}` {c.title}",
                        fw.name if fw else "",
                        m.status if m else "unmapped",
                        m.owner if m and m.status != "implemented" else "",
                    )
                )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def findings_markdown(pack: Pack, findings: list[Finding], rules_run: int) -> str:
    lines = [
        "# govpack check",
        "",
        f"{len(pack.controls)} controls, {len(pack.mappings)} mappings, {rules_run} rules: {len(findings)} findings",
        "",
    ]
    if findings:
        lines += [_row("Severity", "Rule", "Subject", "Message"), _row("---", "---", "---", "---")]
        lines += [_row(f.severity, f.rule, f.subject, f.message) for f in findings]
    return "\n".join(lines) + "\n"


def rules_doc() -> str:
    lines = [HEADER, "# Policy rules", "", "`govpack check` runs these over the pack.", ""]
    lines += [_row("Rule", "Severity", "Requirement", "Why"), _row("---", "---", "---", "---")]
    for rid, sev, title, why in catalog():
        lines.append(_row(f"`{rid}`", sev, title, why))
    return "\n".join(lines) + "\n"


def all_reports(pack: Pack) -> dict[str, str]:
    return {
        "reports/coverage.md": coverage(pack),
        "reports/gap-register.md": gap_register(pack),
        "reports/evidence-index.md": evidence_index(pack),
        "reports/crosswalk.md": crosswalk(pack),
        "reports/system-record.md": system_record(pack),
        "reports/policy-rules.md": rules_doc(),
    }
