from __future__ import annotations

from datetime import date

from govpack import render, rules
from govpack.pack import STATUSES

from .conftest import TODAY


def test_reports_are_deterministic_and_headed(real_pack):
    a = render.all_reports(real_pack)
    b = render.all_reports(real_pack)
    assert a == b and len(a) == 6
    for rel, text in a.items():
        assert text.startswith("<!-- Generated by govpack"), rel
        assert text.endswith("\n") and not text.endswith("\n\n"), rel


def test_every_report_carries_the_notice(real_pack):
    for rel, text in render.all_reports(real_pack).items():
        if rel.endswith("policy-rules.md"):
            continue
        assert "not legal advice" in text, rel


def test_coverage_counts_add_up(real_pack):
    text = render.coverage(real_pack)
    totals = {s: 0 for s in STATUSES}
    for m in real_pack.mappings:
        totals[m.status] += 1
    assert sum(totals.values()) == 41
    row = next(ln for ln in text.splitlines() if ln.startswith("| **All**"))
    cells = [c.strip(" *") for c in row.strip("|").split("|")]
    assert cells[1] == "41" and [int(c) for c in cells[2:]] == [totals[s] for s in STATUSES]
    for c in real_pack.controls:
        assert f"`{c.id}`" in text


def test_gap_register_lists_everything_short_of_implemented_and_nothing_else(real_pack):
    text = render.gap_register(real_pack)
    for m in real_pack.mappings:
        c = real_pack.control(m.control)
        assert c is not None
        listed = f"`{m.control}` {c.title}" in text
        assert listed == (m.status != "implemented"), m.control
    # gaps come first
    first_row = next(ln for ln in text.splitlines() if ln.startswith("| `"))
    assert "| gap |" in first_row


def test_evidence_index_covers_every_locked_file_with_a_short_hash(real_pack):
    text = render.evidence_index(real_pack)
    for key, entry in real_pack.lock.files.items():
        path = key.split(":", 1)[1]
        assert f"`{path}`" in text and entry.sha256[:12] in text
    assert "50 files in 9 registered repositories" in text


def test_crosswalk_only_lists_files_shared_across_frameworks(real_pack):
    text = render.crosswalk(real_pack)
    rows = [ln for ln in text.splitlines() if ln.startswith("| `")]
    assert rows
    for row in rows:
        cells = [c.strip() for c in row.strip("|").split("|")]
        assert sum(1 for c in cells[1:] if c != "-") >= 2, row


def test_system_record_has_components_limits_and_controls(real_pack):
    text = render.system_record(real_pack)
    assert "Customer-support agent" in text and "### Known limitations" in text
    for cid in real_pack.systems[0].controls:
        assert f"`{cid}`" in text
    for comp in real_pack.systems[0].components:
        assert comp.repo in text


def test_table_cells_escape_pipes_and_newlines():
    assert render._esc("a|b\nc") == "a\\|b c"


def test_findings_markdown_without_findings(real_pack):
    text = render.findings_markdown(real_pack, [], 11)
    assert "0 findings" in text and "| Severity" not in text


def test_rules_doc_lists_every_rule(real_pack):
    text = render.rules_doc()
    for rid, *_ in rules.catalog():
        assert f"`{rid}`" in text


def test_a_gap_without_a_mapping_renders_as_unmapped(edit):
    edit.drop_mapping("EUAIA-09")
    text = render.coverage(edit.load())
    assert "unmapped" in text
    assert rules.run(edit.load(), date(2026, 11, 13))[0].rule == "GOV001"
    assert date(2026, 11, 13) == TODAY


def test_reports_do_not_crash_on_an_unknown_status(edit):
    edit.edit_mapping("EUAIA-04", 'status = "organisational"', 'status = "done"')
    pack = edit.load()
    text = render.coverage(pack)
    assert "| done |" in text
    assert sum(render._counts(pack, pack.controls_of("eu-ai-act")).values()) == 12
